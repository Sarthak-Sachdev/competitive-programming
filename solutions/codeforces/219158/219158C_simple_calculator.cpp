#include <bits/stdc++.h>
using namespace std;

int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    long long X, Y;
    cin >> X >> Y;

    cout << X << " + " << Y << " = " << X + Y << '\n';
    cout << X << " * " << Y << " = " << X * Y << '\n';
    cout << X << " - " << Y << " = " << X - Y << '\n';

    return 0;
}
